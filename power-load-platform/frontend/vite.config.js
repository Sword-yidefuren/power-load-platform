import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'

export default defineConfig({
  plugins: [vue()],

  server: {
    port: 5173,

    // ============================================================
    //  开发代理（proxy）—— 解决跨域问题的关键
    // ============================================================
    //  前端的地址是  http://127.0.0.1:5173
    //  后端的地址是  http://127.0.0.1:8080
    //
    //  端口不同 = 浏览器眼里的"不同网站" = 跨域（CORS）。
    //  浏览器默认会拦截这种请求，控制台报：
    //     Access to XMLHttpRequest at 'http://127.0.0.1:8080/api/...'
    //     from origin 'http://127.0.0.1:5173' has been blocked by CORS policy
    //
    //  代理的做法很聪明：让前端只请求"自己家"的地址 /api/xxx，
    //  由 Vite 开发服务器在"背后"转发给 8080。
    //
    //     浏览器 ──> 127.0.0.1:5173/api/...   （同一个源，不跨域！）
    //                      │
    //                      └── Vite 转发 ──> 127.0.0.1:8080/api/...
    //
    //  关键点：浏览器"看不到"这次转发，因为它是服务器之间的通信，
    //  而 CORS 是"浏览器"的安全策略，管不到服务器之间。
    //
    //  这样后端一行代码都不用改 —— 前端代码里写 '/api/stats/...' 就行。
    // ============================================================
    proxy: {
      '/api': {
        target: 'http://127.0.0.1:8080',
        changeOrigin: true
      }
    }
  }
})
